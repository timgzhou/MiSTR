"""Train the paper's runs (exp.mistr.paper_configs: every RunConfig behind a results row), warm-started
runs after the run they start from.

    python -m exp.mistr.paper_runs list  [--tasks pastis ...] [--match REGEX]
    python -m exp.mistr.paper_runs show  RUN_NAME                 # its full config (JSON)
    python -m exp.mistr.paper_runs train [--tasks ...] [--match REGEX] [-- train overrides]
    python -m exp.mistr.paper_runs slurm [--tasks ...] [--match REGEX] [--sbatch "ARGS"] > submit.sh

list: the runs in training order (and which already have a checkpoint). train: trains them here,
one after another (python -m exp.mistr.train --run NAME); a run whose checkpoint exists is skipped,
an interrupted one resumes from checkpoints/<name>_state.pt. slurm: prints one sbatch line per run,
each depending (afterok) on the run it warm-starts from; resources from --sbatch.

Run names end in a hash of every config field set away from its default, so a name pins its
config exactly. Examples:
    python -m exp.mistr.paper_runs list --tasks pastis --match '^fixed_'          # fixed-resolution grid
    python -m exp.mistr.paper_runs train --tasks pastis --match 'S8Tsea\\+S4Tmon_q50_.*seed0'
"""
import argparse
import json
import re
import shlex
import subprocess
import sys
from pathlib import Path

from exp.mistr.paper_configs import by_name

CKPT = Path("checkpoints")


def runs(tasks=None, match=None):
    """{name: (RunConfig, init_from or None)} in dependency order (parents first)."""
    found = {n: (c, c.train.init_from or None) for n, c in by_name().items()
             if not tasks or c.task in tasks}
    if match:
        rx = re.compile(match)
        keep = {n for n in found if rx.search(n)}
        todo = list(keep)               # selected runs pull in the runs they start from
        while todo:
            parent = found[todo.pop()][1]
            if parent and parent in found and parent not in keep:
                keep.add(parent)
                todo.append(parent)
        found = {n: v for n, v in found.items() if n in keep}
    order, seen = [], set()

    def visit(n):
        if n in seen:
            return
        seen.add(n)
        parent = found[n][1]
        if parent in found:
            visit(parent)
        order.append(n)
    for n in found:
        visit(n)
    return {n: found[n] for n in order}


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("cmd", choices=("list", "show", "train", "slurm"))
    ap.add_argument("name", nargs="?", help="show: the run name")
    ap.add_argument("--tasks", nargs="*")
    ap.add_argument("--match", help="regex on the run name")
    ap.add_argument("--sbatch", default="--gres=gpu:1 --cpus-per-task=8 --mem=64G --time=24:00:00",
                    help="slurm: sbatch options for every run")
    ap.add_argument("overrides", nargs="*", help="train: extra dotted overrides (e.g. train.num_workers=4)")
    a = ap.parse_args()
    if a.cmd == "show":
        print(json.dumps(by_name()[a.name].to_dict(), indent=1, sort_keys=True))
        return
    rs = runs(a.tasks, a.match)
    if a.cmd == "list":
        for n, (c, parent) in rs.items():
            done = (CKPT / f"{n}.pt").exists()
            print(f"{'done' if done else 'todo'}  {n}" + (f"   <- {parent}" if parent else ""))
        print(f"{len(rs)} runs, {sum((CKPT / f'{n}.pt').exists() for n in rs)} done", file=sys.stderr)
    elif a.cmd == "train":
        for n in rs:
            if (CKPT / f"{n}.pt").exists():
                print(f"done: {n}")
                continue
            cmd = [sys.executable, "-u", "-m", "exp.mistr.train", "--run", n, *a.overrides]
            print("+", shlex.join(cmd), flush=True)
            subprocess.run(cmd, check=True)
    else:
        print("#!/bin/bash\n# generated by python -m exp.mistr.paper_runs slurm; run from the repo root\nset -e\n"
              "mkdir -p logs\ndeclare -A JOB")
        for n, (c, parent) in rs.items():
            if (CKPT / f"{n}.pt").exists():
                continue
            dep = f'${{JOB[{parent}]:+--dependency=afterok:${{JOB[{parent}]}}}}' if parent in rs else ""
            print(f"JOB[{n}]=$(sbatch --parsable {a.sbatch} {dep} -J {n[:60]} -o logs/%x_%j.out "
                  f"--wrap {shlex.quote(f'python -u -m exp.mistr.train --run {n}')})")


if __name__ == "__main__":
    main()
